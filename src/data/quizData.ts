/**
 * Calculates the exact result among the 4 core archetypes (A, B, C, D):
 * Uses tie-breaker rule from PDF: last answer among tied types wins.
 */
export function calculateQuizResult(answers: Record<number, OptionKey>): QuizResult {
  const counts: Record<OptionKey, number> = { A: 0, B: 0, C: 0, D: 0 };
  const lastAnswers: OptionKey[] = [];

  for (let i = 1; i <= 8; i++) {
    const key = answers[i];
    if (key) {
      counts[key] = (counts[key] || 0) + 1;
      lastAnswers.push(key);
    }
  }

  // Sort keys by frequency; if equal, tie breaker is the latest question answered with that option
  const sorted = (Object.keys(counts) as OptionKey[]).sort((a, b) => {
    if (counts[b] !== counts[a]) {
      return counts[b] - counts[a];
    }
    const lastIndexA = lastAnswers.lastIndexOf(a);
    const lastIndexB = lastAnswers.lastIndexOf(b);
    return lastIndexB - lastIndexA;
  });

  const dominant = sorted[0] || 'A';

  switch (dominant) {
    case 'A':
      return QUIZ_RESULTS.status_recognition; // Персональное внимание ("КОГДА ВАС ЗНАЮТ")
    case 'B':
      return QUIZ_RESULTS.flawless_detail;    // Безупречные детали ("КОГДА ВСЁ УЖЕ ГОТОВО")
    case 'C':
      return QUIZ_RESULTS.absolute_privacy;   // Приватность и пространство ("КОГДА У ВАС ЕСТЬ СВОЁ ПРОСТРАНСТВО")
    case 'D':
    default:
      return QUIZ_RESULTS.time_freedom;       // Время и делегирование ("КОГДА ВРЕМЯ ОСТАЁТСЯ ВАМ")
  }
}
